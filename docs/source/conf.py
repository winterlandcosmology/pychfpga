# Git metadata for published docs (branch picker reads build_info.json).
branch_name = (
    os.environ.get("GITHUB_REF_NAME")
    or ""
)
short_hash = ""
try:
    from git import Repo

    repo = Repo(os.path.abspath("../.."))
    head_commit = repo.head.commit
    short_hash = str(head_commit)[:8]

    if not branch_name:
        try:
            branch_name = repo.active_branch.name
        except TypeError:
            branch_name = ""

    build_info["author_name"] = head_commit.author.name
    build_info["author_email"] = head_commit.author.email
    build_info["author_date"] = head_commit.authored_datetime.isoformat()
    build_info["committer_name"] = head_commit.committer.name
    build_info["committer_email"] = head_commit.committer.email
    build_info["commit_date"] = head_commit.committed_datetime.isoformat()
except Exception as e:
    print(f"{e!r}. Not populating build info except version")

if branch_name and short_hash:
    project = f"pychfpga User Manual ({branch_name} @ {short_hash})"
elif branch_name:
    project = f"pychfpga User Manual ({branch_name})"
else:
    project = "pychfpga User Manual"

